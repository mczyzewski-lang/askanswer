"use client";
import { useState } from "react";
import { Loader2, Shuffle, Sparkles } from "lucide-react";
import type { CallStyle } from "@/lib/editor/types";
import { randomCallerName } from "@/lib/call-names";
import { detectSpeakerGender } from "@/lib/speaker-gender";
import { cn } from "@/lib/utils";
import { useStudio } from "./store";
import { Row, Seg, SButton, Slider, TextField } from "./controls";

type Mode = "off" | CallStyle["mode"];

/** default place of the call bar: centred, at the very top (20 px of 1920) */
const BAR = { x: 0.5, y: 20 / 1920, scale: 1 };

/**
 * "Pytanie jak rozmowa": while the narrator reads the question — a call bar at the top that flies away
 * after the question, or a full-screen call with the expert's face in a circle. The caller gets a
 * random Polish name and the system avatar, or a natural phone "selfie" generated by OpenAI.
 */
export function CallStyleSection({ questionText }: { questionText?: string | null }) {
  const compositionId = useStudio((s) => s.compositionId);
  const cs = useStudio((s) => s.doc?.callStyle);
  const hasNarration = useStudio((s) => (s.doc?.narration.length ?? 0) > 0);
  const assets = useStudio((s) => s.assets);
  const apply = useStudio((s) => s.apply);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const set = (p: Partial<CallStyle> | null) =>
    apply((d) => {
      if (!p) {
        const { callStyle: _drop, ...rest } = d;
        void _drop;
        return rest;
      }
      return { ...d, callStyle: { ...(d.callStyle as CallStyle), ...p } };
    }, `call:${p ? Object.keys(p).join(",") : "off"}`);

  if (!hasNarration) return <p className="text-[12px] text-studio-muted">Dostępne, gdy pytanie czyta lektor ElevenLabs.</p>;

  const mode: Mode = cs?.mode ?? "off";
  const setMode = (m: Mode) => {
    if (m === "off") return set(null);
    if (cs) return set({ mode: m });
    // the caller asks about their own situation, so their words tell the gender ("zamknąłem" / "zamknęłam")
    const gender = detectSpeakerGender(questionText ?? "") ?? "female";
    set({ mode: m, gender, name: randomCallerName(gender), avatarAssetId: null });
  };

  const generate = async () => {
    if (!cs) return;
    setErr(null);
    setBusy(true);
    try {
      const res = await fetch(`/api/admin/compositions/${compositionId}/call-avatar`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ gender: cs.gender, name: cs.name }) });
      const data = await res.json().catch(() => ({}));
      if (!res.ok) throw new Error(data.error ?? `Błąd HTTP ${res.status}`);
      const started = Date.now();
      for (;;) {
        await new Promise((r) => setTimeout(r, 2500));
        const job = await (await fetch(`/api/admin/jobs/${data.jobId}`, { cache: "no-store" })).json().catch(() => null);
        if (job?.status === "FAILED") throw new Error(job.error ?? "Nie udało się wygenerować zdjęcia");
        if (job?.status === "SUCCEEDED") {
          const st = useStudio.getState();
          st.addAssets(job.assets ?? []);
          const ids: string[] = job.result?.variantIds ?? [];
          st.apply((d) => (d.callStyle ? { ...d, callStyle: { ...d.callStyle, avatarVariants: [...ids, ...(d.callStyle.avatarVariants ?? [])].slice(0, 12), avatarAssetId: ids[0] ?? d.callStyle.avatarAssetId } } : d), "call-avatar");
          break;
        }
        if (Date.now() - started > 4 * 60_000) throw new Error("Generowanie trwa zbyt długo — spróbuj ponownie.");
      }
    } catch (e) {
      setErr((e as Error).message);
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="space-y-2.5" data-testid="call-style">
      <Seg<Mode>
        value={mode}
        onChange={setMode}
        options={[
          ["off", "Zwykle"],
          ["bar", "Pasek rozmowy"],
          ["phone", "Ekran rozmowy"],
        ]}
      />
      <p className="text-[11.5px] leading-snug text-studio-muted">
        {mode === "bar"
          ? "U góry pasek trwającego połączenia; po pytaniu odlatuje w górę i znika."
          : mode === "phone"
            ? "Na cały ekran telefon w trakcie rozmowy, ekspert w kółku; po pytaniu ekran odjeżdża."
            : "Pytanie jak rozmowa telefoniczna — w czasie, gdy lektor je czyta."}
      </p>
      {cs?.mode === "bar" ? (
        <div className="space-y-1.5" data-testid="call-bar-layout">
          <Row label={`Rozmiar: ${Math.round((cs.bar?.scale ?? 1) * 100)}%`}>
            <Slider value={cs.bar?.scale ?? 1} min={0.5} max={1.6} step={0.05} onChange={(v) => set({ bar: { ...BAR, ...cs.bar, scale: v } })} aria-label="Rozmiar paska rozmowy" format={(v) => `${Math.round(v * 100)}%`} />
          </Row>
          <Row label="Pozycja w pionie">
            <Slider value={cs.bar?.y ?? BAR.y} min={0} max={0.9} step={0.005} onChange={(v) => set({ bar: { ...BAR, ...cs.bar, y: v } })} aria-label="Pozycja paska w pionie" format={(v) => `${Math.round(v * 100)}%`} />
          </Row>
          <Row label="Pozycja w poziomie">
            <Slider value={cs.bar?.x ?? BAR.x} min={0.2} max={0.8} step={0.005} onChange={(v) => set({ bar: { ...BAR, ...cs.bar, x: v } })} aria-label="Pozycja paska w poziomie" format={(v) => `${Math.round(v * 100)}%`} />
          </Row>
          <p className="text-[11px] leading-snug text-studio-muted">
            Pasek możesz też przeciągnąć na podglądzie (w czasie pytania).{" "}
            {cs.bar ? (
              <button className="underline" onClick={() => set({ bar: undefined })}>
                Domyślnie
              </button>
            ) : null}
          </p>
        </div>
      ) : null}
      {cs ? (
        <>
          <Row label="Rozmówca">
            <span className="flex items-center gap-1.5">
              <TextField value={cs.name} onChange={(e) => set({ name: e.target.value })} aria-label="Imię rozmówcy" maxLength={60} />
              <SButton variant="ghost" onClick={() => set({ name: randomCallerName(cs.gender, cs.name) })} title="Losuj imię" aria-label="Losuj imię">
                <Shuffle />
              </SButton>
            </span>
          </Row>
          <Row label="Płeć">
            <Seg value={cs.gender} onChange={(g) => set({ gender: g, name: randomCallerName(g) })} options={[["female", "Kobieta"], ["male", "Mężczyzna"]]} />
          </Row>
          <div className="space-y-1.5">
            <p className="text-[11.5px] text-studio-muted">Zdjęcie rozmówcy</p>
            <div className="grid grid-cols-4 gap-1.5">
              <button
                type="button"
                onClick={() => set({ avatarAssetId: null })}
                aria-pressed={!cs.avatarAssetId}
                aria-label="Awatar systemowy"
                className={cn("flex aspect-square items-center justify-center rounded-full border-2 bg-gradient-to-b from-[#a3a8b4] to-[#7d838f] text-lg font-semibold text-white", !cs.avatarAssetId ? "border-emerald-400" : "border-transparent")}
              >
                {(cs.name.trim()[0] ?? "?").toUpperCase()}
              </button>
              {(cs.avatarVariants ?? []).map((id, i) => (
                <button
                  key={id}
                  type="button"
                  onClick={() => set({ avatarAssetId: id })}
                  aria-pressed={cs.avatarAssetId === id}
                  aria-label={`Zdjęcie ${i + 1}`}
                  data-testid="call-avatar-variant"
                  className={cn("overflow-hidden rounded-full border-2", cs.avatarAssetId === id ? "border-emerald-400" : "border-transparent hover:border-white/30")}
                >
                  {assets[id] ? (
                    // eslint-disable-next-line @next/next/no-img-element
                    <img src={assets[id].url} alt="" className="aspect-square w-full object-cover" />
                  ) : (
                    <div className="aspect-square w-full bg-studio-3" />
                  )}
                </button>
              ))}
            </div>
            <SButton className="w-full" onClick={generate} disabled={busy} data-testid="call-avatar-generate">
              {busy ? <Loader2 className="animate-spin" /> : <Sparkles />} {busy ? "OpenAI robi zdjęcie…" : "Wygeneruj zdjęcie (OpenAI)"}
            </SButton>
            <p className="text-[11px] leading-snug text-studio-muted">Naturalne „selfie” z telefonu — średni kąt, zwykłe światło, nie zdjęcie od fotografa.</p>
          </div>
        </>
      ) : null}
      {err ? <p className="text-[12px] text-red-300">{err}</p> : null}
    </div>
  );
}
